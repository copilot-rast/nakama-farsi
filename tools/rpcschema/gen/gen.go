package gen

import (
	"bytes"
	"encoding/json"
	"os"
	"path/filepath"
)

type Document struct {
	Comment   string    `json:"$comment"`
	Version   int       `json:"version"`
	Transport Transport `json:"transport"`
	RPCs      []RPC     `json:"rpcs"`
}

type Transport struct {
	Call         string            `json:"call"`
	Auth         map[string]string `json:"auth"`
	ErrorFormats map[string]string `json:"errorFormats"`
	ErrorCatalog string            `json:"errorCatalog"`
}

func Build(root string, modules []Module) (codes []byte, schema []byte, err error) {
	found, err := ScanCodes(root, modules)
	if err != nil {
		return nil, nil, err
	}
	codes, err = marshal(found)
	if err != nil {
		return nil, nil, err
	}
	rpcs, err := ScanRPCs(root, modules)
	if err != nil {
		return nil, nil, err
	}
	doc := Document{
		Comment: "Generated by tools/rpcschema from the nakama-farsi Go sources; do not edit by hand.",
		Version: 1,
		Transport: Transport{
			Call: "POST /v2/rpc/{id}?unwrap with the request object as the JSON body (or socket rpc with the same payload); the response body is the response object.",
			Auth: map[string]string{
				"session": "Authorization: Bearer <session token>",
				"apikey":  "X-Api-Key: <key> on the devkit HTTP endpoints",
			},
			ErrorFormats: map[string]string{
				"code":     "error message is the bare error code (e.g. GIFT_EXPIRED); map it to text with devkit_error_catalog",
				"json":     "error message is a JSON object {code,status,meta}; map code to text with devkit_error_catalog",
				"envelope": "error message is a JSON envelope {code,status,message,meta,retryAfterSeconds,lang} already localized; in code mode (errors.mode for apierr.RPC RPCs, errors.moduleMode for RPCs with codeModeFormat, the default for those) it is a bare code, or the codeModeFormat shape",
			},
			ErrorCatalog: "rpc devkit_error_catalog {lang} or GET /v2/devkit/errors?lang=fa",
		},
		RPCs: rpcs,
	}
	schema, err = marshal(doc)
	return codes, schema, err
}

func marshal(v any) ([]byte, error) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(v); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func Write(root, outDir string, modules []Module) error {
	codes, schema, err := Build(root, modules)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(outDir, "codes.json"), codes, 0o644); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(outDir, "rpc-schema.json"), schema, 0o644)
}

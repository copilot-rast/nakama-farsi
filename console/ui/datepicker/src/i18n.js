function ndt(key, vars) {
  var table = ND_TEXT[ndLang()] || ND_TEXT.en;
  var s = table[key];
  if (s === undefined) s = ND_TEXT.en[key];
  if (s === undefined) return key;
  if (vars) s = s.replace(/\{(\w+)\}/g, function (m, k) { return vars[k] === undefined ? m : String(vars[k]); });
  return s;
}

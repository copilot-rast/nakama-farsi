function plLang() {
  var l = (document.documentElement.getAttribute('lang') || 'fa').toLowerCase();
  return l.indexOf('fa') === 0 ? 'fa' : 'en';
}

function plNum(n) {
  var s = String(n);
  if (plLang() !== 'fa') return s;
  return s.replace(/[0-9]/g, function (d) { return '۰۱۲۳۴۵۶۷۸۹'[d]; });
}

function pst(key, vars) {
  var cat = PL_MESSAGES[plLang()] || PL_MESSAGES.en;
  var s = cat[key] !== undefined ? cat[key] : (PL_MESSAGES.en[key] !== undefined ? PL_MESSAGES.en[key] : key);
  if (vars) s = s.replace(/\{(\w+)\}/g, function (m, k) { return vars[k] === undefined ? m : typeof vars[k] === 'number' ? plNum(vars[k]) : vars[k]; });
  return s;
}

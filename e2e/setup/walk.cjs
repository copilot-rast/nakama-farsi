const L = require('./lib.cjs');
const path = require('path');

(async () => {
  const reset = await L.adminFetch('PUT', '/v2/console/base/setup', { status: 'pending' });
  L.check(reset.status === 200 && reset.data.status === 'pending', 'setup reset to pending for a fresh-server run');
  const b = await L.browser();
  const { page } = await L.context(b);
  await page.goto(L.URL + '/#/login');
  await page.waitForSelector('input[name="username"]');
  await L.shot(page, '00-login-default-fa');
  await L.login(page);
  await page.waitForSelector('[data-economy="setup"]', { timeout: 8000 }).catch(() => {});
  L.check(await L.wizardOpen(page), 'wizard opened by itself after first login');
  await L.waitStep(page, 'brand');
  await L.shot(page, '01-brand-fa-light');

  const name = page.locator('[data-economy="setup"] [data-translated="name"]');
  await name.locator('[role="tabpanel"][data-lang="fa"] input').fill('ستاره‌چین');
  await name.locator('[role="tab"][data-lang="en"]').click();
  await name.locator('[role="tabpanel"][data-lang="en"] input').fill('Starpicker');
  const shortName = page.locator('[data-economy="setup"] input[aria-label="نام کوتاه"]');
  await shortName.fill('ستاره');
  const files = page.locator('[data-economy="setup"] input[type="file"]');
  await files.nth(0).setInputFiles(path.join(L.ASSETS, 'logo.svg'));
  await page.waitForTimeout(800);
  await files.nth(1).setInputFiles(path.join(L.ASSETS, 'logo-dark.svg'));
  await page.waitForTimeout(800);
  await files.nth(2).setInputFiles(path.join(L.ASSETS, 'mark.svg'));
  await page.waitForTimeout(800);
  const hex = page.locator('[data-economy="setup"] .brand-hex input');
  await hex.fill('#ffee00');
  await page.waitForTimeout(300);
  const poor = await page.evaluate(() => [...document.querySelectorAll('[data-contrast]')].map((e) => e.textContent).join(' | '));
  console.log('contrast for #ffee00:', poor);
  L.check(/کم‌کنتراست|فقط برای متن درشت/.test(poor), 'contrast check flags a pale yellow');
  await hex.fill('zz');
  await L.next(page);
  await page.waitForTimeout(600);
  const colorErr = await page.evaluate(() => { const f = document.querySelector('[data-economy="setup"] .eco-invalid'); return f ? f.textContent : ''; });
  L.check(/هگز/.test(colorErr), 'invalid color shows an error next to the field');
  await page.click('[data-economy="setup"] .brand-swatch[data-color="#059669"]');
  await page.waitForTimeout(300);
  await L.shot(page, '02-brand-filled-fa-light');
  await L.next(page);
  await L.waitStep(page, 'languages');
  const applied = await page.evaluate(() => ({
    title: document.title,
    favicon: document.querySelector('link[rel~="icon"]').getAttribute('href'),
    p500: getComputedStyle(document.documentElement).getPropertyValue('--primary-color-500').trim()
  }));
  console.log('applied', JSON.stringify(applied));
  L.check(/ستاره‌چین/.test(applied.title), 'title uses the brand name');
  L.check(/\/v2\/economy\/files\/.+\.svg$/.test(applied.favicon), 'favicon is the uploaded mark');
  L.check(applied.p500 === '5 150 105', 'accent variables follow #059669');
  await L.shot(page, '03-languages-fa-light');

  const arToggle = page.locator('[data-economy="setup"] li[data-lang="ar"] .x-toggle');
  await arToggle.click();
  await page.waitForTimeout(1200);
  const arOff = await L.api(page, 'GET', '/v2/console/base/languages/ar');
  L.check(arOff.data.isActive === false, 'turning a language off saves it at once');
  await page.locator('[data-economy="setup"] li[data-lang="ar"] .x-toggle').click();
  await page.waitForTimeout(1200);
  await page.click('[data-economy="setup"] [data-add-lang="tr"]');
  await page.waitForSelector('[data-economy="setup"] li[data-lang="tr"]', { timeout: 6000 });
  L.check(true, 'quick add created tr');
  await L.shot(page, '04-languages-added-fa-light');
  await L.next(page);
  await L.waitStep(page, 'currency');
  await L.shot(page, '05-currency-fa-light');
  const dv = page.locator('[data-economy="setup"] input[aria-label="موجودی اول"]');
  await dv.fill('۱۲۰');
  await L.next(page);
  await L.waitStep(page, 'payment');
  const coin = await L.api(page, 'GET', '/v2/console/economy/currencies?limit=10');
  const c = coin.data.items.find((x) => x.key === 'coin');
  L.check(c && c.defaultValue === 120 && c.name.fa === 'سکه' && c.sort === 1, 'currency saved through the economy API with Persian digits converted, other fields kept');
  await L.shot(page, '06-payment-fa-light');
  const zibal = page.locator('[data-economy="setup"] [data-method="zibal"]');
  const zibalOn = await zibal.evaluate((el) => el.classList.contains('setup-method--on'));
  if (!zibalOn) await zibal.locator('[data-pick-method="zibal"]').click();
  const sandboxOn = await zibal.locator('[data-sandbox-box]').evaluate((el) => el.classList.contains('eco-sandbox-note'));
  L.check(sandboxOn, 'zibal sandbox is on');
  await zibal.locator('input[aria-label="کد مرچنت"]').fill('zibal');
  await L.shot(page, '07-payment-zibal-fa-light');
  await L.next(page);
  await L.waitStep(page, 'sms');
  const pm = await L.api(page, 'GET', '/v2/console/economy/payment-methods');
  const z = pm.data.find((m) => m.method === 'zibal');
  L.check(z.isActive && z.config.sandbox === true && z.configured, 'zibal saved active in sandbox');
  await L.shot(page, '08-sms-fa-light');
  await page.click('[data-economy="setup"] [data-need] [data-value="no"]');
  await page.waitForTimeout(300);
  await L.shot(page, '09-sms-no-fa-light');
  await L.next(page);
  await L.waitStep(page, 'email');
  let st = await L.api(page, 'GET', '/v2/console/base/setup');
  console.log('steps', JSON.stringify(st.data.steps), st.data.status);
  L.check(st.data.steps.sms === 'skipped' && st.data.steps.brand === 'done' && st.data.steps.payment === 'done', 'step states stored');

  await page.click('[data-economy="setup"] .setup-step[data-step="brand"]');
  await L.waitStep(page, 'brand');
  L.check((await L.stepTitle(page)) === 'برند پروژه', 'step bar jumps back to brand');
  const kept = await page.locator('[data-economy="setup"] [data-translated="name"] [role="tabpanel"][data-lang="fa"] input').inputValue();
  L.check(kept === 'ستاره‌چین', 'brand step pre-fills saved values');
  await page.click('[data-economy="setup"] .setup-step[data-step="email"]');
  await L.waitStep(page, 'email');
  await L.shot(page, '10-email-fa-light');
  await page.click('[data-economy="setup"] [data-setup-later]');
  await page.waitForTimeout(800);
  L.check(!(await L.wizardOpen(page)), 'later closes the wizard');
  st = await L.api(page, 'GET', '/v2/console/base/setup');
  L.check(st.data.status === 'skipped' && st.data.nextStep === 'email', 'later marks skipped and keeps progress');
  await L.shot(page, '11-sidebar-branded-fa-light');

  await page.evaluate(() => { location.hash = '#/settings/setup'; });
  await page.waitForSelector('[data-setup-row]', { timeout: 10000 });
  await L.shot(page, '12-settings-setup-fa-light');
  await page.click('[data-setup-open]');
  await L.waitStep(page, 'email');
  L.check(true, 'reopen resumes at the first unfinished step (email)');
  await page.click('[data-economy="setup"] [data-need] [data-value="yes"]').catch(() => {});
  const kind = await page.evaluate(() => { const b = document.querySelector('[data-economy="setup"] [data-kind] [aria-checked="true"]'); return b && b.getAttribute('data-value'); });
  if (kind !== 'smtp') await page.click('[data-economy="setup"] [data-kind] [data-value="smtp"]');
  const smtpSandbox = await page.locator('[data-economy="setup"] [data-sandbox-box]').first().evaluate((el) => el.classList.contains('eco-sandbox-note'));
  L.check(smtpSandbox, 'smtp sandbox is on');
  await page.fill('[data-economy="setup"] input[aria-label="گیرنده"]', 'qa@example.com');
  await page.click('[data-economy="setup"] button:has-text("ذخیره و ارسال آزمایشی")');
  await page.waitForSelector('[data-economy="setup"] [data-test-result]', { timeout: 10000 });
  const res = await page.evaluate(() => document.querySelector('[data-economy="setup"] [data-test-result]').getAttribute('data-test-result'));
  L.check(res === 'sandbox', 'email test-send answered from sandbox, nothing sent');
  await L.shot(page, '13-email-tested-fa-light');
  await L.next(page);
  await L.waitStep(page, 'review');
  await page.waitForSelector('[data-economy="setup"] [data-review]', { timeout: 10000 });
  await L.shot(page, '14-review-fa-light');
  await page.click('[data-economy="setup"] [data-setup-next]');
  await page.waitForTimeout(1200);
  L.check(!(await L.wizardOpen(page)), 'finish closes the wizard');
  st = await L.api(page, 'GET', '/v2/console/base/setup');
  L.check(st.data.status === 'completed' && st.data.completedBy === L.ADMIN.user, 'setup completed by admin');
  await page.evaluate(() => { location.hash = '#/'; });
  await page.waitForTimeout(1500);
  await L.shot(page, '15-dashboard-branded-fa-light');
  await b.close();
})().catch((e) => { console.error(e); process.exit(1); });
